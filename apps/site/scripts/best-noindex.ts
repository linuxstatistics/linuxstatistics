// Writes src/config/noindex.js: pages built with a robots noindex and kept out of
// the sitemap. Two sources: /best/ topics with too few qualifying picks, and
// article topic hubs with fewer than MIN_HUB_ARTICLES published articles.
// Run after changing profiles, topics or published articles:
//   pnpm --filter @linux-statistics/site best:noindex
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { BEST_TOPICS, MIN_PICKS, bestPicks, isIndexable } from "../src/lib/best-for";
import { PROFILES } from "../src/lib/picker-profiles";
import { articleFrontmatter, readingMinutes, thinHubPaths, toCard } from "../src/lib/articles";
import { MIN_HUB_ARTICLES } from "../src/lib/article-topics";
import { readFrontmatter } from "../src/lib/frontmatter";

const thinBest = BEST_TOPICS.filter((t) => !isIndexable(bestPicks(t, PROFILES, () => null))).map((t) => `/best/${t.slug}/`);

// Published articles only (the repo folder); drafts never count toward a hub.
const dir = new URL("../src/content/articles/", import.meta.url);
const cards = readdirSync(dir)
  .filter((f) => f.endsWith(".md"))
  .map((f) => {
    const fm = readFrontmatter(readFileSync(new URL(f, dir), "utf8"));
    if (!fm) throw new Error(`${f}: no front matter`);
    const parsed = articleFrontmatter.safeParse(fm.data);
    if (!parsed.success) throw new Error(`${f}: ${parsed.error.issues.map((i) => `${i.path.join(".")}: ${i.message}`).join("; ")}`);
    return toCard(f.replace(/\.md$/, ""), parsed.data, readingMinutes(fm.body), false);
  });
const thinHubs = thinHubPaths(cards);

const all = [...thinBest, ...thinHubs].sort();
const body = `/**
 * Paths built with a robots noindex, kept out of the sitemap. Generated by
 * \`pnpm --filter @linux-statistics/site best:noindex\` from the /best/ topic guard
 * (fewer than ${MIN_PICKS} qualifying picks) and the article hub guard (fewer than
 * ${MIN_HUB_ARTICLES} published articles); tests check it is current.
 */
export const NOINDEX_PATHS = ${JSON.stringify(all, null, 2)};
`;
writeFileSync(new URL("../src/config/noindex.js", import.meta.url), body);
console.log(`best:noindex: ${all.length} noindex path(s): ${all.join(", ") || "none"}`);
for (const t of BEST_TOPICS) console.log(`  best/${t.slug}: ${bestPicks(t, PROFILES, () => null).map((p) => p.key).join(" ")}`);
console.log(`  published articles: ${cards.length}`);
